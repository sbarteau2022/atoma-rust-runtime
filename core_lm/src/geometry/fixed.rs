//! Q32.31 Fixed-Point Arithmetic
//! Used for the H³/Γ address path to ensure total determinism.

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct Q32_31(pub i64);

impl Q32_31 {
    pub const FRACTIONAL_BITS: u32 = 31;
    pub const ONE: Self = Self(1i64 << Self::FRACTIONAL_BITS);
    pub const ZERO: Self = Self(0);
    pub const HALF: Self = Self(1i64 << (Self::FRACTIONAL_BITS - 1));
    pub const MIN: Self = Self(i64::MIN);
    pub const MAX: Self = Self(i64::MAX);

    #[inline]
    pub fn from_f64(val: f64) -> Self {
        if val.is_nan() {
            return Self::ZERO;
        }
        let scaled = (val * (1i64 << Self::FRACTIONAL_BITS) as f64).round();
        if scaled >= i64::MAX as f64 {
            Self::MAX
        } else if scaled <= i64::MIN as f64 {
            Self::MIN
        } else {
            Self(scaled as i64)
        }
    }

    #[inline]
    pub fn to_f64(self) -> f64 {
        (self.0 as f64) / (1i64 << Self::FRACTIONAL_BITS) as f64
    }

    #[inline]
    pub fn abs(self) -> Self {
        Self(self.0.saturating_abs())
    }

    #[inline]
    pub const fn saturating_add(self, other: Self) -> Self {
        Self(self.0.saturating_add(other.0))
    }

    #[inline]
    pub const fn saturating_sub(self, other: Self) -> Self {
        Self(self.0.saturating_sub(other.0))
    }

    #[inline]
    pub fn saturating_mul(self, other: Self) -> Self {
        self.mul(other)
    }

    #[inline]
    pub const fn saturating_neg(self) -> Self {
        Self(self.0.saturating_neg())
    }

    pub fn checked_add(self, other: Self) -> Option<Self> {
        self.0.checked_add(other.0).map(Self)
    }

    pub fn checked_sub(self, other: Self) -> Option<Self> {
        self.0.checked_sub(other.0).map(Self)
    }

    #[inline]
    pub fn mul(self, other: Self) -> Self {
        let res = (self.0 as i128 * other.0 as i128) >> Self::FRACTIONAL_BITS;
        Self(res.clamp(i64::MIN as i128, i64::MAX as i128) as i64)
    }

    #[inline]
    pub fn div(self, other: Self) -> Self {
        if other.0 == 0 {
            return if self.0 == 0 {
                Self::ZERO
            } else if self.0 > 0 {
                Self::MAX
            } else {
                Self::MIN
            };
        }
        let res = ((self.0 as i128) << Self::FRACTIONAL_BITS) / other.0 as i128;
        Self(res.clamp(i64::MIN as i128, i64::MAX as i128) as i64)
    }

    pub fn sqrt(self) -> Self {
        if self.0 <= 0 {
            return Self::ZERO;
        }

        let mut x = self;
        for _ in 0..10 {
            if x.0 <= 0 {
                return Self::ZERO;
            }
            let s_div_x = self.div(x);
            let sum = (x.0 as i128) + (s_div_x.0 as i128);
            x = Self((sum >> 1).clamp(0, i64::MAX as i128) as i64);
        }
        x
    }

    pub fn inv_sqrt(self) -> Self {
        if self.0 <= 0 {
            return Self::MAX;
        }
        let root = self.sqrt();
        if root.0 <= 0 {
            return Self::MAX;
        }
        Self::ONE.div(root)
    }

    pub fn sin(self) -> Self {
        Self::lut_interp(self, true)
    }

    pub fn cos(self) -> Self {
        Self::lut_interp(self, false)
    }

    fn lut_interp(self, is_sin: bool) -> Self {
        // 2 * PI * 2^31
        const TWO_PI: i64 = 13492913325;
        let mut theta = self;

        let t0 = theta.0;
        let rem = t0 % TWO_PI;
        theta = Self(if rem < 0 { rem + TWO_PI } else { rem });

        const LUT_SIZE: usize = 256;
        let step = TWO_PI / LUT_SIZE as i64;

        let idx = ((theta.0 / step) as usize) % LUT_SIZE;
        let frac_val = theta.0.saturating_sub(idx as i64 * step);
        let frac = Self(frac_val);

        let val1 = if is_sin { SIN_LUT[idx] } else { COS_LUT[idx] };
        let val2 = if is_sin {
            SIN_LUT[(idx + 1) % LUT_SIZE]
        } else {
            COS_LUT[(idx + 1) % LUT_SIZE]
        };

        Self(val1).saturating_add(frac.mul(Self(val2).saturating_sub(Self(val1))))
    }
}

